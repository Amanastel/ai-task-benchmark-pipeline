"""Stage 1d -- linting and formatting.

Uses ruff for both, because one pinned binary doing check + format removes a
whole class of "black and flake8 disagree" configuration work, and because it
runs fast enough to sit inside the validation loop.

Two things here are judgement calls worth stating plainly:

*Baselining.* Adopting a linter on a repo that never had one leaves violations
no autofix can safely resolve. Rewriting them by hand is a behavioural change
the pipeline should not make unattended, so the remaining rules are moved into
an explicit, commented ``extend-ignore`` baseline with per-rule counts written
to ``.okf/lint.json``. The repo is then genuinely lint-clean under a config
that is honest about what it postponed -- as opposed to lint-clean because the
config selects nothing.

*Formatting is reverted on regression.* ``ruff format`` touches every file. If
reformatting changes a test verdict, the formatter is the problem, so the
caller rolls the tree back and we record it rather than shipping a repo whose
suite the pipeline itself broke.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .. import util
from . import dockerenv
from .detect import RepoProfile

RUFF_CONFIG_NAMES = (".ruff.toml", "ruff.toml")

SELECTED_RULES = ["E", "F", "W", "I", "UP", "B", "C4", "RUF"]

# Rules that fight normal library code or duplicate the formatter's job.
ALWAYS_IGNORE = [
    ("E501", "line length is the formatter's job, not the linter's"),
    ("E203", "conflicts with the formatter's slice spacing"),
    ("B008", "function call in argument default is a deliberate idiom in many APIs"),
    ("RUF012", "mutable class attrs without ClassVar are pervasive in untyped code"),
]


@dataclass
class LintResult:
    ok: bool
    config_path: str = ""
    formatted_files: int = 0
    fixed_violations: int = 0
    baselined: dict[str, int] = field(default_factory=dict)
    remaining: int = 0
    format_reverted: bool = False
    mode: str = "fix+format"      # which rung of the ladder was kept
    log: str = ""
    notes: list[str] = field(default_factory=list)


def find_existing_config(repo: Path) -> str:
    for name in RUFF_CONFIG_NAMES:
        if (repo / name).exists():
            return name
    txt = util.read_text(repo / "pyproject.toml", "")
    if "[tool.ruff" in txt:
        return "pyproject.toml"
    return ""


def render_config(prof: RepoProfile, extend: str = "",
                  baseline: dict[str, int] | None = None) -> str:
    py_tag = "py" + prof.python_version.replace(".", "")
    lines: list[str] = []
    A = lines.append
    A("# Generated by okfpipe (stage 1).")
    A("#")
    A("# ruff is used for both linting and formatting so there is exactly one")
    A("# tool, one config and one version pinned in requirements.lock.")
    A("")
    if extend:
        A(f'extend = "{extend}"  # the repo already had ruff config; it still wins')
        A("")
    A("line-length = 100")
    A(f'target-version = "{py_tag}"')
    A("")
    A("extend-exclude = [")
    for d in ("build", "dist", "docs", ".tox", ".nox", "*.egg-info", "vendor",
              "third_party", "_vendor"):
        A(f'    "{d}",')
    A("]")
    A("")
    A("[lint]")
    A("select = [" + ", ".join(f'"{r}"' for r in SELECTED_RULES) + "]")
    A("")
    A("ignore = [")
    for code, why in ALWAYS_IGNORE:
        A(f'    "{code}",  # {why}')
    if baseline:
        A("")
        A("    # --- adoption baseline -------------------------------------------")
        A("    # Pre-existing violations that no autofix can resolve safely. Each")
        A("    # line records how many sites remain; see .okf/lint.json. Removing")
        A("    # an entry here is the unit of work for paying the debt down.")
        for code, count in sorted(baseline.items()):
            A(f'    "{code}",  # {count} pre-existing occurrence'
              f'{"s" if count != 1 else ""}')
    A("]")
    A("")
    A("[lint.per-file-ignores]")
    A('# Tests legitimately shadow names, assert on unused values and import lazily.')
    A('"**/test_*.py" = ["F401", "F811", "F841", "B011", "E731"]')
    A('"**/tests/**" = ["F401", "F811", "F841", "B011", "E731"]')
    A('"**/conftest.py" = ["F401", "F811"]')
    A('"__init__.py" = ["F401", "F403"]  # re-exports are the whole point')
    A("")
    A("[format]")
    A('quote-style = "preserve"      # do not churn every string literal')
    A('indent-style = "space"')
    A("skip-magic-trailing-comma = false")
    A("docstring-code-format = false  # never rewrite doctest bodies")
    A("")
    return "\n".join(lines)


_COUNT_RE = re.compile(r"^(?P<code>[A-Z]+\d+)\b", re.M)


def _violation_counts(json_like_output: str) -> dict[str, int]:
    """Count violations per rule from ruff's concise output."""
    counts: dict[str, int] = {}
    for line in json_like_output.splitlines():
        # concise format: path:line:col: CODE message
        m = re.search(r":\d+:\d+:\s+([A-Z]+\d+)\b", line)
        if m:
            counts[m.group(1)] = counts.get(m.group(1), 0) + 1
    return counts


def _ruff(image: str, repo: Path, args: list[str], timeout: int = 900) -> util.Result:
    return dockerenv.run_in(
        image, ["python", "-m", "ruff", *args],
        mounts=[dockerenv.Mount(repo, "/app")],
        workdir="/app", network="none", timeout=timeout)


def apply(prof: RepoProfile, repo: Path, image: str, do_format: bool = True,
          do_fix: bool = True) -> LintResult:
    """Write config, optionally autofix and format, then baseline what is left.

    ``do_fix`` exists because "safe fix" is ruff's judgement, not a guarantee.
    On the held-out repo, ``UP017`` rewrote ``return timezone.utc`` into
    ``return UTC`` inside a ``try:`` block whose ``except ImportError:`` branch
    was the only thing that defined ``UTC`` -- a labelled-safe fix that broke a
    test. The caller runs this in a ladder and falls back to config-only, so a
    repo whose code cannot be touched safely still ends up lint-clean with its
    behaviour intact.
    """
    existing = find_existing_config(repo)
    extend = existing if existing in RUFF_CONFIG_NAMES else ""
    notes: list[str] = []
    if existing:
        notes.append(f"repo already configured ruff in {existing}; "
                     + ("extending it" if extend else "our config takes precedence"))

    config_name = "ruff.toml" if existing != "ruff.toml" else ".ruff.toml"
    if extend == config_name:  # do not extend ourselves
        config_name = ".ruff.toml" if config_name == "ruff.toml" else "ruff.toml"

    util.write_text(repo / config_name, render_config(prof, extend))
    logs: list[str] = []

    before = _ruff(image, repo, ["check", "--config", config_name, "--statistics", "."])
    logs.append("$ ruff check --statistics (before)\n" + util.truncate(before.output, 2500, 1500))

    fixed = 0
    if do_fix:
        # Safe fixes only: an unsafe fix is one ruff itself says may change
        # behaviour, which is exactly what we must not do to an unfamiliar repo.
        fix = _ruff(image, repo, ["check", "--config", config_name, "--fix",
                                  "--no-unsafe-fixes", "."])
        logs.append("$ ruff check --fix\n" + util.truncate(fix.output, 2500, 1500))
        m = re.search(r"(\d+)\s+fixed", fix.output)
        if m:
            fixed = int(m.group(1))

    formatted = 0
    if do_format:
        fmt = _ruff(image, repo, ["format", "--config", config_name, "."])
        logs.append("$ ruff format\n" + util.truncate(fmt.output, 2000, 1000))
        m = re.search(r"(\d+)\s+files?\s+reformatted", fmt.output)
        if m:
            formatted = int(m.group(1))
        if do_fix:
            # Formatting can introduce new lint findings; fix those too.
            _ruff(image, repo, ["check", "--config", config_name, "--fix",
                                "--no-unsafe-fixes", "."])

    after = _ruff(image, repo, ["check", "--config", config_name, "."])
    logs.append("$ ruff check (after fixes)\n" + util.truncate(after.output, 3000, 2000))
    remaining_counts = _violation_counts(after.output)

    if remaining_counts:
        util.write_text(repo / config_name,
                        render_config(prof, extend, baseline=remaining_counts))
        notes.append(f"baselined {sum(remaining_counts.values())} pre-existing "
                     f"violations across {len(remaining_counts)} rules")

    final = _ruff(image, repo, ["check", "--config", config_name, "."])
    logs.append("$ ruff check (final, with baseline)\n"
                + util.truncate(final.output, 2000, 1500))
    final_count = sum(_violation_counts(final.output).values())

    util.info("lint applied", fixed=fixed, formatted=formatted,
              baselined=len(remaining_counts), remaining=final_count)

    return LintResult(
        ok=final.ok and final_count == 0,
        config_path=config_name,
        formatted_files=formatted,
        fixed_violations=fixed,
        baselined=remaining_counts,
        remaining=final_count,
        log="\n\n".join(logs),
        notes=notes,
    )
