"""Stage 3c -- the validation harness.

Runs over any task folder and emits a verdict. Everything the task claims is
re-derived here by executing the task's *own* ``verifier/run.sh``, so the
evidence and the grader's reproduction run the same command rather than two
implementations that happen to agree today.

Five gates, all required:

``imports``          ``input/`` imports cleanly. A task whose before-state is
                     broken is a broken task, not a hard one.
``collects``         pytest can collect the verifier against ``input/``.
                     Separates "red" from "does not run", which is the
                     distinction the brief draws.
``fail_before``      the verifier fails against ``input/`` *and* the failure is
                     classified behavioural -- an assertion about behaviour,
                     not an ImportError.
``pass_after``       the verifier passes against ``solution/``.
``determinism``      both runs repeated N times produce identical outcome
                     fingerprints, not merely identical exit codes.
``no_collateral``    no test that passes against ``input/``'s full suite fails
                     against ``solution/``'s. Comparing regressions rather than
                     demanding a wholly green suite keeps the check honest on
                     historical trees that had pre-existing failures.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .. import util
from ..hygiene import dockerenv
from . import runner

RUN_SH = """#!/bin/sh
# Generated by okfpipe (stage 3).
#
#   verifier/run.sh <tree>            e.g. verifier/run.sh input
#
# Copies <tree> and this directory's overlay into a scratch working copy, then
# runs exactly the test selection this task is graded on. The tree passed in is
# never modified, so the same command can be run against input/ and solution/
# repeatedly without resetting anything.
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
TREE=${1:?usage: run.sh <tree> [extra pytest args...]}
shift || true

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

cp -a "$TREE/." "$WORK/"
if [ -d "$HERE/overlay" ]; then
    cp -a "$HERE/overlay/." "$WORK/"
fi

cd "$WORK"
unset PYTEST_ADDOPTS 2>/dev/null || true
export PYTHONHASHSEED=0
export PYTHONPATH="$WORK"

# xargs keeps one node id per line intact even when a parametrised id contains
# spaces; without -d there is no safe way to pass them through.
SELECTION=$(tr '\\n' ' ' < "$HERE/selection.txt")

# shellcheck disable=SC2086
exec python -m pytest $SELECTION -p no:cacheprovider -q --timeout=180 "$@"
"""


@dataclass
class Verdict:
    task_id: str
    valid: bool = False
    gates: dict = field(default_factory=dict)
    repeats: int = 0
    notes: list[str] = field(default_factory=list)

    def to_json(self) -> dict:
        return {
            "task_id": self.task_id,
            "valid": self.valid,
            "gates": self.gates,
            "determinism_repeats": self.repeats,
            "notes": self.notes,
        }


def write_verifier(task_dir: Path, selection: list[str],
                   overlay: dict[str, str]) -> None:
    vdir = task_dir / "verifier"
    vdir.mkdir(parents=True, exist_ok=True)
    util.write_text(vdir / "selection.txt", "\n".join(selection) + "\n")
    p = util.write_text(vdir / "run.sh", RUN_SH)
    try:
        p.chmod(0o755)
    except OSError:
        pass
    for rel, content in (overlay or {}).items():
        util.write_text(vdir / "overlay" / rel, content)
    if not overlay:
        # Keep the directory shape uniform across task kinds.
        (vdir / "overlay").mkdir(parents=True, exist_ok=True)
        util.write_text(vdir / "overlay" / ".gitkeep", "")


def _run_verifier(image: str, task_dir: Path, tree: str, workdir: Path,
                  label: str, timeout: int = 900) -> runner.Outcome:
    """Execute the task's own verifier/run.sh inside the pinned image."""
    outdir = workdir / f"junit-{util.slugify(label)}"
    util.rmtree(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    res = dockerenv.run_in(
        image,
        ["sh", "-c", f"/task/verifier/run.sh /task/{tree} "
                     "--junitxml=/out/junit.xml"],
        mounts=[dockerenv.Mount(task_dir, "/task", "ro"),
                dockerenv.Mount(outdir, "/out")],
        workdir="/task", network="none", timeout=timeout)
    outcomes, messages, counts = runner.parse_junit(outdir / "junit.xml")
    return runner.Outcome(
        exit_code=res.returncode, outcomes=outcomes, messages=messages,
        collected=counts["collected"], passed=counts["passed"],
        failed=counts["failed"], errors=counts["errors"],
        skipped=counts["skipped"], duration_s=round(res.duration_s, 2),
        log=util.truncate(res.output, 2500, 5000))


def _full_suite(image: str, tree: Path, workdir: Path, test_paths: list[str],
                label: str) -> runner.Outcome:
    return runner.run_pytest(image, tree, workdir, list(test_paths),
                             label=label, timeout=1800)


def validate(task_dir: Path, image: str, packages: list[str],
             test_paths: list[str], workdir: Path, repeats: int = 3) -> Verdict:
    task = util.read_json(task_dir / "task.json", {}) or {}
    verdict = Verdict(task_id=task.get("id", task_dir.name), repeats=repeats)
    ev = task_dir / "evidence"
    ev.mkdir(parents=True, exist_ok=True)
    workdir.mkdir(parents=True, exist_ok=True)

    selection = [ln.strip() for ln in
                 util.read_text(task_dir / "verifier" / "selection.txt", "").splitlines()
                 if ln.strip()]

    # ---- gate 1: input/ imports ----------------------------------------
    ok, log = runner.import_check(image, task_dir / "input", packages)
    verdict.gates["imports"] = {"passed": ok, "detail": log[-800:]}
    util.write_text(ev / "import_check.log", log)

    # ---- gate 2: the verifier collects against input/ -------------------
    collect_tree = workdir / "collect"
    runner.materialise(task_dir / "input", collect_tree,
                       overlay_dir=task_dir / "verifier" / "overlay")
    cok, clog = runner.collect_check(image, collect_tree, workdir, selection)
    verdict.gates["collects"] = {"passed": cok, "detail": clog[-800:]}
    util.write_text(ev / "collect_check.log", clog)
    util.rmtree(collect_tree)

    # ---- gate 3: fail-before, for the right reason ----------------------
    before = _run_verifier(image, task_dir, "input", workdir, "fail-before")
    kind = before.failure_kind()
    fail_before_ok = (
        not before.ok
        and before.collected > 0
        and bool(before.failing())
        and kind == "behavioural"
    )
    # The run's own stats are nested rather than spread: Outcome.to_json() has
    # its own "passed" key holding a test *count*, and spreading it here would
    # overwrite this gate's pass/fail boolean with a number -- making the gate
    # report on how many tests passed rather than on whether it was satisfied.
    verdict.gates["fail_before"] = {
        "passed": fail_before_ok,
        "failure_kind": kind,
        "requirement": "verifier must fail against input/ with a behavioural "
                       "assertion, not an import or collection error",
        "run": before.to_json(),
    }
    util.write_json(ev / "fail_before.json", {
        **before.to_json(),
        "failure_messages": {k: v[:1500] for k, v in
                             list(before.messages.items())[:10]},
    })
    util.write_text(ev / "fail_before.log", before.log)

    # ---- gate 4: pass-after ---------------------------------------------
    after = _run_verifier(image, task_dir, "solution", workdir, "pass-after")
    verdict.gates["pass_after"] = {
        "passed": after.ok,
        "requirement": "verifier must pass cleanly against solution/",
        "run": after.to_json(),
    }
    util.write_json(ev / "pass_after.json", after.to_json())
    util.write_text(ev / "pass_after.log", after.log)

    # ---- gate 5: determinism --------------------------------------------
    before_prints = [before.fingerprint]
    after_prints = [after.fingerprint]
    before_exits = [before.exit_code]
    after_exits = [after.exit_code]
    for i in range(2, repeats + 1):
        b = _run_verifier(image, task_dir, "input", workdir, f"fail-before-{i}")
        a = _run_verifier(image, task_dir, "solution", workdir, f"pass-after-{i}")
        before_prints.append(b.fingerprint)
        after_prints.append(a.fingerprint)
        before_exits.append(b.exit_code)
        after_exits.append(a.exit_code)

    det_ok = len(set(before_prints)) == 1 and len(set(after_prints)) == 1
    verdict.gates["determinism"] = {
        "passed": det_ok,
        "repeats": repeats,
        "input_fingerprints": before_prints,
        "solution_fingerprints": after_prints,
        "input_exit_codes": before_exits,
        "solution_exit_codes": after_exits,
        "requirement": "identical per-test outcome fingerprints across repeats, "
                       "not merely identical exit codes",
    }
    util.write_json(ev / "determinism.json", verdict.gates["determinism"])

    # ---- gate 6: no collateral breakage ---------------------------------
    suite_before = _full_suite(image, task_dir / "input", workdir, test_paths,
                               "suite-input")
    suite_after = _full_suite(image, task_dir / "solution", workdir, test_paths,
                              "suite-solution")
    regressed = sorted(
        t for t, status in suite_before.outcomes.items()
        if status == "passed" and suite_after.outcomes.get(t, "missing")
        in ("failed", "error"))
    collateral_ok = not regressed
    verdict.gates["no_collateral"] = {
        "passed": collateral_ok,
        "regressed_tests": regressed[:40],
        "regressed_count": len(regressed),
        "input_suite": {"passed": suite_before.passed, "failed": suite_before.failed,
                        "errors": suite_before.errors,
                        "collected": suite_before.collected},
        "solution_suite": {"passed": suite_after.passed, "failed": suite_after.failed,
                           "errors": suite_after.errors,
                           "collected": suite_after.collected},
        "requirement": "no test passing on input/ may fail on solution/",
    }
    util.write_json(ev / "no_collateral_breakage.json", verdict.gates["no_collateral"])
    util.write_text(ev / "no_collateral_breakage.log",
                    "=== full suite against input/ ===\n" + suite_before.log
                    + "\n\n=== full suite against solution/ ===\n" + suite_after.log)

    # `is True` rather than truthiness: a gate must report a boolean, so a
    # non-boolean sneaking into that slot fails loudly instead of being counted
    # as a pass because it happened to be a non-zero number.
    verdict.valid = all(g.get("passed") is True for g in verdict.gates.values())
    if not verdict.valid:
        failed = [k for k, g in verdict.gates.items() if not g.get("passed")]
        verdict.notes.append("failed gate(s): " + ", ".join(failed))

    util.write_json(ev / "verdict.json", verdict.to_json())
    util.info("task validated", task=verdict.task_id,
              valid=str(verdict.valid),
              gates=",".join(k for k, g in verdict.gates.items() if g.get("passed")))
    return verdict
